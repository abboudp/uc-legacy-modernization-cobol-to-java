package com.carddemo.posting;

/**
 * Raised where the legacy program would {@code DISPLAY} a file status and call {@code CEE3ABD}: a record
 * that cannot be decoded, or a dataset operation that COBOL treats as unrecoverable.
 */
public class PostingDataException extends RuntimeException {

    public PostingDataException(String message) {
        super(message);
    }
}
